-- ============================================================
-- Scholary · 014: чистим названия стран в каталоге
--
-- ЗАЧЕМ. В каталоге одна и та же страна была записана двумя способами:
-- «Британия» и «Великобритания», «Сауд. Аравия» и «Саудовская Аравия».
-- В кабинете это давало два отдельных пункта в фильтре стран, а на сайте
-- завышало счётчик стран (получалось 57 вместо реальных 56).
-- Идемпотентно.
-- ============================================================

update programs set country = 'Великобритания'   where country = 'Британия';
update programs set country = 'Саудовская Аравия' where country = 'Сауд. Аравия';

-- ---------- проверка ----------
select count(*) as programs_total,
       count(distinct country) as country_values
from programs;

select country, count(*) as programs
from programs
group by country
having country in ('Великобритания','Саудовская Аравия','Британия','Сауд. Аравия')
order by country;
