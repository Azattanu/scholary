<?php
/* Scholary · уведомления владельцу о новой заявке.
   Вызывается с сайта сразу после формы заявки.
   Получатель ЖЁСТКО задан в конфиге (почта и WhatsApp Азата), поэтому
   эндпоинт нельзя использовать как чужой ретранслятор спама.
   Данные заявки приходят с клиента (у нас нет сервисного ключа Supabase),
   поэтому они чистятся и обрезаются, а частота ограничена по IP.
   Факт ОПЛАТЫ сюда не приходит — его присылает шлюз в api/tiptop.php. */
require __DIR__ . '/_lib.php';
cors();
if (($_SERVER['REQUEST_METHOD'] ?? '') !== 'POST') jout(['error' => 'method'], 405);

/* Форму отправляет наш же сайт. Запрос «в лоб» с чужой страницы отсекаем:
   иначе эндпоинт превращается в кнопку «завалить владельца сообщениями». */
if (!same_origin()) jout(['error' => 'forbidden'], 403);

$in = body(20000);

/* ---------- защита от флуда ---------- */
$rl = rate_check('ip:' . client_ip() . ':notify', 12);
if (!$rl['ok']) jout(['error' => 'too_many'], 429);
$rlAll = rate_check('all:notify', 150);
if (!$rlAll['ok']) jout(['error' => 'paused'], 429);

/* ---------- разбор заявки ---------- */
$name  = clean_txt($in['name'] ?? '', 80);
$phone = clean_txt($in['phone'] ?? '', 32);
$email = clean_txt($in['email'] ?? '', 120);
if ($name === '' && $phone === '' && $email === '') jout(['error' => 'empty'], 400);

$sent = notify_owner('Новая заявка с сайта', [
  'Имя'         => $name ?: '—',
  'Телефон'     => $phone ?: '—',
  'Почта'       => $email ?: '—',
  'Уровень'     => clean_txt($in['level'] ?? '', 40) ?: '—',
  'Страница'    => clean_txt($in['page'] ?? '', 120) ?: '—',
  'Комментарий' => clean_txt($in['note'] ?? '', 600) ?: '—',
  'ID лида'     => clean_txt($in['lead_id'] ?? '', 64) ?: '—',
]);

jout(['ok' => true, 'sent' => $sent]);
